cand = set(words)
for n in (2, 3):
    for combo in itertools.product(words, repeat=n):
        cand.add('_'.join(combo))
print('candidates:', len(cand))

found = {}
for s in cand:
    h = dek(s)
    if h in UNK:
        found.setdefault(h, []).append(s)

named = 0
for h in sorted(UNK):
    if h in found:
        print('  0x%08X = %-24s  (%s)' % (h, ' | '.join(sorted(found[h]))[:40], UNK[h]))
        named += 1
    else:
        print('  0x%08X = %-24s  (%s)' % (h, '???', UNK[h]))
